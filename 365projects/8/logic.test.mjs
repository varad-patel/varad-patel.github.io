import test from "node:test";
import assert from "node:assert/strict";
import { WELLBEING } from "../data/wellbeing.js";
import { FIRST_YEAR, incomePath, simulate, halfLife, countrySeries, countriesWithSeries, crossSection, predict, fitCountry, changes } from "./logic.js";

const close = (a, b, tol = 1e-9) => assert.ok(Math.abs(a - b) <= tol, `${a} is not within ${tol} of ${b}`);

test("income paths: steady growth, a lasting jump and a jump that is taken away", () => {
  assert.deepEqual(incomePath({ years: 3, start: 100, growth: 0.1, change: 0 }).map((v) => Math.round(v)), [100, 110, 121]);
  assert.deepEqual(incomePath({ years: 5, start: 100, change: 0.5, changeYear: 2 }), [100, 100, 150, 150, 150]);
  assert.deepEqual(incomePath({ years: 6, start: 100, change: 0.5, changeYear: 2, lasts: 2 }), [100, 100, 150, 150, 100, 100]);
  assert.deepEqual(incomePath({ years: 4, start: 100, change: -0.2, changeYear: 1 }), [100, 80, 80, 80]);
});

test("a one-off raise lifts happiness by b times the log gain, then fades towards b x gain x (1 - k)", () => {
  const b = 0.8, alpha = 0.3, k = 0.8, gain = Math.log(1.5);
  const sim = simulate(incomePath({ years: 40, change: 0.5, changeYear: 5 }), { alpha, k, b, base: 5 });
  close(sim.happiness[4], 5);
  close(sim.happiness[5], 5 + b * gain);
  // n years after the raise the lift is b x gain x (1 - k (1 - (1 - alpha)^n)).
  for (const n of [1, 2, 5, 10]) close(sim.happiness[5 + n], 5 + b * gain * (1 - k * (1 - (1 - alpha) ** n)), 1e-12);
  close(sim.happiness[39], 5 + b * gain * (1 - k), 1e-4);
  close(sim.noAdaptation[39], 5 + b * gain);
  close(sim.reference[39], 20000 * 1.5, 1);
});

test("with k = 0 there is no adaptation, and with alpha = 0 the reference level never moves", () => {
  const incomes = incomePath({ years: 20, growth: 0.03, change: 0.4, changeYear: 3 });
  const none = simulate(incomes, { alpha: 0.5, k: 0, b: 1 });
  none.happiness.forEach((h, i) => close(h, none.noAdaptation[i], 1e-12));
  const frozen = simulate(incomes, { alpha: 0, k: 1, b: 1 });
  frozen.reference.forEach((r) => close(r, incomes[0], 1e-6));
  frozen.happiness.forEach((h, i) => close(h, frozen.noAdaptation[i], 1e-12));
});

test("the treadmill: under full adaptation steady growth buys a constant lift of b x g / alpha, and stopping loses it", () => {
  const g = Math.log(1.02), alpha = 0.25, b = 0.8;
  const sim = simulate(incomePath({ years: 200, growth: 0.02, change: 0 }), { alpha, k: 1, b, base: 5 });
  close(sim.happiness[199], 5 + (b * g) / alpha, 1e-6);
  assert.ok(sim.noAdaptation[199] > 8);
  // Growth for 30 years and then none: the lift decays back to the starting level.
  const stop = [...incomePath({ years: 30, growth: 0.02, change: 0 })];
  for (let i = 0; i < 60; i++) stop.push(stop[29]);
  close(simulate(stop, { alpha, k: 1, b, base: 5 }).happiness.at(-1), 5, 1e-6);
});

test("uneven gaps between observations compound the yearly rate", () => {
  const yearly = simulate([100, 150, 150, 150, 150], { alpha: 0.3, k: 1, b: 1, base: 0 });
  const skipped = simulate([100, 150, 150], { alpha: 0.3, k: 1, b: 1, base: 0, times: [0, 1, 4] });
  close(skipped.happiness[2], yearly.happiness[4], 1e-12);
  close(skipped.reference[2], yearly.reference[4], 1e-9);
});

test("half-life of adaptation", () => {
  close(halfLife(0.5), 1);
  close(halfLife(0.3), Math.log(0.5) / Math.log(0.7));
  assert.equal(halfLife(0), Infinity);
  // With alpha = 1 the whole gap closes at once, which is the limit of the formula. The readout must never go
  // back up as the rate rises (it used to jump from 0.2 years at 0.95 to 1 year at 1).
  assert.equal(halfLife(1), 0);
  for (let a = 0.05; a < 1; a += 0.05) assert.ok(halfLife(a + 0.05) < halfLife(a), `half-life falls as alpha rises past ${a.toFixed(2)}`);
  // The definition itself: after halfLife years, half of a gap is left.
  close((1 - 0.3) ** halfLife(0.3), 0.5, 1e-12);
});

test("fitCountry recovers the parameters of a series generated by the model", () => {
  const years = Array.from({ length: 14 }, (_, i) => 2011 + i);
  const gdp = years.map((_, i) => 10000 * 1.06 ** i * (i >= 6 ? 1.3 : 1));
  const truth = simulate(gdp, { alpha: 0.4, k: 0.6, b: 0.8, base: 5, times: years });
  const series = years.map((year, i) => ({ year, gdp: gdp[i], ladder: truth.happiness[i] }));
  const fit = fitCountry(series, 0.8);
  close(fit.k, 0.6, 1e-9);
  close(fit.alpha, 0.4, 1e-9);
  close(fit.rmse, 0, 1e-9);
  assert.ok(fit.rmseNone > 0.05 && fit.rmseFlat > 0.05);
  assert.ok(fit.nearlyAsGood > 0 && fit.nearlyAsGood < 0.05);
  const p = predict(series, { alpha: 0.4, k: 0.6, b: 0.8 });
  p.fitted.forEach((v, i) => close(v, series[i].ladder, 1e-9));
});

test("changes: slope of change in life evaluation on change in income", () => {
  const toy = { years: [2000, 2010], countries: [
    { name: "A", gdp: [100, 200], ladder: [5, 6] },
    { name: "B", gdp: [100, 400], ladder: [5, 7] },
    { name: "C", gdp: [100, 100], ladder: [5, 5] },
    { name: "D", gdp: [100, null], ladder: [5, 9] },
  ] };
  const ch = changes(toy, 2000, 2010);
  assert.equal(ch.n, 3);
  close(ch.slope, 1);
  close(ch.intercept, 0);
  assert.deepEqual(ch.rows.find((r) => r.name === "B"), { name: "B", dIncome: 2, dLadder: 2 });
});

test("real data: series, cross-section and the finding on the page", () => {
  // The report's 2011 point pools surveys from 2005 to mid-2011, so the data module leaves it out and the series
  // starts at 2012 (surveys of 2010 to 2012).
  assert.equal(FIRST_YEAR, 2012);
  assert.equal(WELLBEING.years[0], 2012);
  const india = countrySeries(WELLBEING, "India");
  assert.equal(india.length, 13);
  assert.equal(india[0].year, 2012);
  assert.equal(india.at(-1).year, 2025);
  // Spot checks against the sources: World Happiness Report 2026 (India 4.536, rank 116) and the World Bank's
  // GDP per person for 2023, 2024 and 2025 (8,870.55, 9,416.05 and 10,039.07), averaged.
  assert.equal(india.at(-1).ladder, 4.536);
  assert.equal(india.at(-1).gdp, Math.round((8870.55027609345 + 9416.05137044735 + 10039.0708910587) / 3));
  assert.equal(countriesWithSeries(WELLBEING, 8).length, 146);
  assert.ok(india.every((p) => p.gdp > 0 && p.ladder > 0));
  assert.deepEqual(countrySeries(WELLBEING, "Atlantis"), []);
  assert.ok(countriesWithSeries(WELLBEING, 8).length > 120);

  const cs = crossSection(WELLBEING, 2025);
  assert.equal(cs.n, 144);
  close(cs.perDoubling, 0.548, 0.001);
  close(cs.b, 0.790, 0.001);
  const ch = changes(WELLBEING, FIRST_YEAR, 2025);
  assert.equal(ch.n, 139);
  close(ch.slope, 1.036, 0.001);
  close(1.96 * ch.se, 0.313, 0.001);
  assert.ok(ch.slope - 1.96 * ch.se > 0.7);
  close(ch.r2, 0.236, 0.001);
  // The other two starting points offered on the page also give a slope clearly above zero.
  for (const from of [2015, 2019]) { const c = changes(WELLBEING, from, 2025); assert.ok(c.slope - 1.96 * c.se > 0.5, String(from)); }
  // Richer and less satisfied over the window.
  for (const name of ["India", "Ireland", "United States"]) {
    const r = ch.rows.find((x) => x.name === name);
    assert.ok(r.dIncome > 0 && r.dLadder < 0, name);
  }
  const fit = fitCountry(india, cs.b);
  assert.ok(fit.rmse <= fit.rmseNone);
});
