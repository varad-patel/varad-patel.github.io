// UC Berkeley graduate admissions, autumn 1973, six largest departments: [men admitted, men rejected, women admitted, women rejected].
const BERKELEY = { A: [512, 313, 89, 19], B: [353, 207, 17, 8], C: [120, 205, 202, 391], D: [138, 279, 131, 244], E: [53, 138, 94, 299], F: [22, 351, 24, 317] };
// Kidney stone treatments (Charig et al., 1986): [treatment, stone size, successes, patients].
const KIDNEY = [["A (open surgery)", "small", 81, 87], ["A (open surgery)", "large", 192, 263], ["B (percutaneous)", "small", 234, 270], ["B (percutaneous)", "large", 55, 80]];

function berkeleyCsv() {
  const rows = [["department", "gender", "decision", "applicants"]];
  for (const [dept, [ma, mr, wa, wr]] of Object.entries(BERKELEY)) {
    rows.push([dept, "men", "admitted", ma], [dept, "men", "rejected", mr], [dept, "women", "admitted", wa], [dept, "women", "rejected", wr]);
  }
  return csv.stringify(rows);
}
function kidneyCsv() {
  const rows = [["treatment", "stone_size", "outcome", "patients"]];
  for (const [t, size, ok, n] of KIDNEY) rows.push([t, size, "success", ok], [t, size, "failure", n - ok]);
  return csv.stringify(rows);
}

/**
 * A made-up population in which the truth is known: cholesterol = 140 + 2.2 age - 7 exercise + noise,
 * and older people exercise more (exercise = 0.12 age - 1 + noise). One row per person.
 */
export function syntheticCsv(seed = 14, n = 300) {
  const r = rng(seed);
  const rows = [["age", "age_group", "exercise_hours", "cholesterol"]];
  for (let i = 0; i < n; i++) {
    const age = r.int(20, 69);
    const exercise = Math.max(0, 0.12 * age - 1 + r.normal(0, 1));
    const cholesterol = 140 + 2.2 * age - 7 * exercise + r.normal(0, 8);
    rows.push([age, `${Math.floor(age / 10) * 10}s`, exercise.toFixed(1), Math.round(cholesterol)]);
  }
  return csv.stringify(rows);
}

