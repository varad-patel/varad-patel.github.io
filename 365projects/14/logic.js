/* ------------------------------------------------------------------- reading */

/** "1,234.5", "3,5", "45%", "£12" and "1e3" all read as numbers. Anything else is NaN. */
export function toNumber(s) {
  let t = String(s).replace(/[\s£$€%]/g, "");
  if (/^-?\d{1,3}(,\d{3})+(\.\d+)?$/.test(t)) t = t.replace(/,/g, "");
  else if (/^-?\d+,\d+$/.test(t)) t = t.replace(",", ".");
  if (t === "") return NaN;
  const v = Number(t);
  return Number.isFinite(v) ? v : NaN;
}

/** Delimited text to columns of trimmed strings: { names, raw, n, warnings } or { error }. */
export function parseTable(text) {
  if (typeof text !== "string" || !text.trim()) return { error: "There is no data yet. Paste CSV text, drop a file or pick an example." };
  if (text.includes("\u0000")) return { error: "This looks like a spreadsheet or another binary file, not text. Save it as CSV (comma-separated values) and try again." };
  const grid = csv.parse(text);
  const head = grid[0] || [];
  if (grid.length < 2) return { error: "Only one line of text was found. The first line must hold the column names, with the data on the lines below it." };
  if (head.length < 3) {
    return { error: `Only ${plural(head.length, "column")} found. The search needs at least three: an outcome, something to compare, and something to split by. Columns can be separated by commas, tabs or semicolons.` };
  }
  const seen = new Map();
  const names = head.map((h, i) => {
    const name = h.trim() || `column ${i + 1}`;
    const k = (seen.get(name) || 0) + 1;
    seen.set(name, k);
    return k > 1 ? `${name} (${k})` : name;
  });
  const total = grid.length - 1;
  const n = Math.min(total, LIMITS.rows);
  const raw = names.map(() => new Array(n));
  let ragged = 0;
  for (let i = 0; i < n; i++) {
    const r = grid[i + 1];
    if (r.length !== names.length) ragged++;
    for (let j = 0; j < names.length; j++) raw[j][i] = (r[j] ?? "").trim();
  }
  if (ragged > n / 2) {
    return { error: `${ragged} of ${plural(n, "line")} do not have ${names.length} cells like the header line. Check that every line uses the same separator and that quotation marks are closed.` };
  }
  const warnings = [];
  if (ragged) warnings.push(`${plural(ragged, "line")} had more or fewer than ${names.length} cells. Missing cells were read as blank and extra cells were ignored.`);
  if (total > n) warnings.push(`The file has ${total.toLocaleString("en-GB")} rows. Only the first ${n.toLocaleString("en-GB")} were read.`);
  return { names, raw, n, warnings };
}

/**
 * Work out what each column is.
 *   kind "numeric"  a measure with three or more different values (num holds the values, NaN where missing)
 *   kind "binary"   exactly two different values (y01 holds 0 and 1; `positive` is the level counted as 1)
 *   kind "category" three to twelve different text values
 *   kind "ignored"  empty, constant, or text with too many different values (reason says which)
 * Any column with at most twelve different values also gets `levels` and `codes`, so it can define groups.
 */
export function profile(table) {
  return table.names.map((name, index) => {
    const raw = table.raw[index];
    const n = table.n;
    let missing = 0, numbers = 0;
    const num = new Float64Array(n);
    for (let i = 0; i < n; i++) {
      if (MISSING.has(raw[i].toLowerCase())) { missing++; num[i] = NaN; continue; }
      num[i] = toNumber(raw[i]);
      if (num[i] === num[i]) numbers++;
    }
    const present = n - missing;
    const numeric = present > 0 && numbers / present >= 0.95;
    const unparsed = numeric ? present - numbers : 0;
    const col = { name, index, missing: missing + unparsed, unparsed, numeric, kind: "ignored", reason: "", distinct: 0, many: false, num: numeric ? num : null, levels: null, codes: null };
    if (!present) { col.reason = "empty"; return col; }

    // Different values, up to the most a grouping column may have.
    const seen = new Map();
    const key = (i) => (numeric ? (num[i] === num[i] ? String(num[i]) : null) : (MISSING.has(raw[i].toLowerCase()) ? null : raw[i]));
    for (let i = 0; i < n && !col.many; i++) {
      const k = key(i);
      if (k != null && !seen.has(k)) { seen.set(k, 0); if (seen.size > LIMITS.levels) col.many = true; }
    }
    col.distinct = seen.size;
    if (!col.many) {
      col.levels = [...seen.keys()].sort(numeric ? (a, b) => Number(a) - Number(b) : (a, b) => a.localeCompare(b, "en", { numeric: true }));
      const code = new Map(col.levels.map((l, j) => [l, j]));
      col.codes = new Int32Array(n);
      for (let i = 0; i < n; i++) { const k = key(i); col.codes[i] = k == null ? -1 : code.get(k); }
    }
    if (numeric) {
      let s = 0;
      for (let i = 0; i < n; i++) if (num[i] === num[i]) s += num[i];
      col.centre = s / numbers;
    }

    if (col.distinct === 1) col.reason = "the same value in every row";
    else if (col.distinct === 2) {
      col.kind = "binary";
      const named = col.levels.map((l) => POSITIVE.has(l.toLowerCase()));
      col.positive = named[0] && !named[1] ? 0 : 1;
      col.y01 = new Float64Array(n);
      for (let i = 0; i < n; i++) col.y01[i] = col.codes[i] < 0 ? NaN : col.codes[i] === col.positive ? 1 : 0;
    } else if (numeric) col.kind = "numeric";
    else if (col.many) col.reason = `more than ${LIMITS.levels} different text values, so it reads as a name or an identifier`;
    else col.kind = "category";
    return col;
  });
}

/** Columns that could be a count of identical rows: numbers, none missing, none negative. */
export const weightable = (cols) => cols.filter((c) => c.numeric && c.missing === 0 && c.num.every((v) => v >= 0) && c.num.some((v) => v > 0));

/**
 * Guess whether the table is already counted up. Returns the index of the count column or null.
 * A column is taken as a count when it holds whole numbers and either has a telling name, or is the only
 * measure in a table whose other columns never repeat a combination (so each row is one cell of a cross-tabulation).
 */
export function guessWeight(cols, n) {
  const whole = weightable(cols).filter((c) => c.num.every((v) => Number.isInteger(v)) && c.num.some((v) => v > 1));
  const named = whole.find((c) => /^(n|count|counts|freq|frequency|weight|weights|number|total|cases)$/i.test(c.name));
  if (named) return named.index;
  if (whole.length !== 1) return null;
  const others = cols.filter((c) => c !== whole[0] && c.kind !== "ignored");
  if (others.length < 3 || others.some((c) => !c.codes)) return null;
  const combos = new Set();
  for (let i = 0; i < n; i++) combos.add(others.map((c) => c.codes[i]).join(","));
  return combos.size === n ? whole[0].index : null;
}

/* ----------------------------------------------------------------- the search */

/** Everything a comparison needs: the columns, the row weights and the smallest group to keep. Returns { error } for a bad count column. */
export function context(table, cols, { weight = null, minCell = 5 } = {}) {
  let w = null;
  if (weight != null) {
    const c = cols[weight];
    if (!c || !c.numeric) return { error: `The count column must hold numbers, and "${c ? c.name : weight}" does not.` };
    if (c.num.some((v) => v < 0)) return { error: `The count column "${c.name}" has negative values. A count of rows cannot be negative.` };
    w = c.num;
  }
  let total = 0;
  for (let i = 0; i < table.n; i++) { const v = w ? w[i] : 1; if (v > 0) total += v; }
  return { n: table.n, cols, w, weight, total, minCell: Math.max(1, minCell), bins: new Map() };
}

/** Cut a numeric column into thirds holding equal numbers of observations: { levels, codes }. */
export function thirds(col, ctx) {
  if (ctx.bins.has(col.index)) return ctx.bins.get(col.index);
  const { n, w } = ctx;
  const idx = [];
  let total = 0;
  for (let i = 0; i < n; i++) if (col.num[i] === col.num[i] && (!w || w[i] > 0)) { idx.push(i); total += w ? w[i] : 1; }
  idx.sort((a, b) => col.num[a] - col.num[b]);
  const cuts = [];
  let cum = 0, next = 1;
  for (const i of idx) {
    cum += w ? w[i] : 1;
    while (next <= 2 && cum >= (total * next) / 3 - 1e-9) { cuts.push(col.num[i]); next++; }
  }
  const [c1, c2] = cuts;
  const f = (v) => String(Number(v.toPrecision(4)));
  const levels = c1 === c2 ? [`up to ${f(c1)}`, `over ${f(c1)}`] : [`up to ${f(c1)}`, `${f(c1)} to ${f(c2)}`, `over ${f(c2)}`];
  const codes = new Int32Array(n);
  for (let i = 0; i < n; i++) {
    const v = col.num[i];
    codes[i] = v !== v ? -1 : v <= c1 ? 0 : c1 === c2 ? 1 : v <= c2 ? 1 : 2;
  }
  const out = { levels, codes };
  ctx.bins.set(col.index, out);
  return out;
}

export const groupsOf = (job, ctx) => (job.binned ? thirds(ctx.cols[job.z], ctx) : ctx.cols[job.z]);

/**
 * List every triple worth testing as { kind, y, x, z, binned } (column indexes).
 *   two measures                -> "slope": the later column on the earlier one
 *   a measure and a category    -> "diff": the mean of the measure, between two levels of the category
 *   a binary and a category     -> "diff": the rate of the binary, between two levels of the category
 *   two binaries                -> "diff": the rate of the later one, between the two levels of the earlier one
 * and z is any other column with 2 to 12 values, or a measure cut into thirds.
 */
export function plan(cols, { weight = null, thirds: bin = true } = {}) {
  const use = cols.filter((c) => c.kind !== "ignored" && c.index !== weight);
  const jobs = [];
  for (let i = 0; i < use.length; i++) for (let j = i + 1; j < use.length; j++) {
    const p = use[i], q = use[j];
    const pm = p.kind === "numeric", qm = q.kind === "numeric";
    let kind, y, x;
    if (pm && qm) { kind = "slope"; x = p; y = q; }
    else if (pm !== qm) { kind = "diff"; y = pm ? p : q; x = pm ? q : p; }
    else if (q.kind === "binary") { kind = "diff"; y = q; x = p; }
    else if (p.kind === "binary") { kind = "diff"; y = p; x = q; }
    else continue;
    for (const z of use) {
      if (z === p || z === q) continue;
      if (z.codes) jobs.push({ kind, y: y.index, x: x.index, z: z.index, binned: false });
      else if (bin && z.kind === "numeric") jobs.push({ kind, y: y.index, x: x.index, z: z.index, binned: true });
    }
  }
  return { jobs: jobs.slice(0, LIMITS.jobs), skipped: Math.max(0, jobs.length - LIMITS.jobs) };
}

const zscore = (effect, se) => (se > 0 ? effect / se : effect === 0 ? 0 : Math.sign(effect) * 1e6);

// Shared ending: count the groups on each side and decide whether the direction reverses.
function verdict(result, groupEffects) {
  const dir = Math.sign(result.overall.effect);
  result.opposed = groupEffects.filter((e) => Math.sign(e) === -dir && dir !== 0).length;
  result.same = groupEffects.filter((e) => Math.sign(e) === dir && dir !== 0).length;
  result.kept = groupEffects.length;
  const flips = dir !== 0 && Math.sign(result.within.effect) === -dir;
  result.reversal = !flips ? null : result.opposed === result.kept ? "full" : "partial";
  result.strength = Math.min(Math.abs(result.overall.z), Math.abs(result.within.z));
  return result;
}

function diffPair(job, ctx, g, cell, a, b, swapped = false) {
  const Y = ctx.cols[job.y], X = ctx.cols[job.x], L = X.levels.length;
  const binary = Y.kind === "binary";
  const c0 = binary ? 0 : Y.centre;
  const least = Math.max(ctx.minCell, binary ? 1 : 2);
  // Variance of a mean. For a rate this is p(1 - p)/n; for a measure it is the sample variance over n.
  const varMean = (n, s, q) => Math.max(0, q / n - (s / n) ** 2) * (binary ? 1 : n / (n - 1)) / n;
  const groups = [];
  const A = { n: 0, s: 0, q: 0 }, B = { n: 0, s: 0, q: 0 };
  let dropped = 0, minCell = Infinity;
  for (let k = 0; k < g.levels.length; k++) {
    const ia = k * L + a, ib = k * L + b;
    const na = cell.n[ia], nb = cell.n[ib];
    if (na + nb === 0) continue;
    const kept = na >= least && nb >= least;
    const ma = na ? cell.s[ia] / na : NaN, mb = nb ? cell.s[ib] / nb : NaN;
    groups.push({ level: g.levels[k], na, nb, a: ma + c0, b: mb + c0, effect: ma - mb, kept, v: kept ? varMean(na, cell.s[ia], cell.q[ia]) + varMean(nb, cell.s[ib], cell.q[ib]) : NaN });
    if (!kept) { dropped += na + nb; continue; }
    A.n += na; A.s += cell.s[ia]; A.q += cell.q[ia];
    B.n += nb; B.s += cell.s[ib]; B.q += cell.q[ib];
    minCell = Math.min(minCell, na, nb);
  }
  const keptGroups = groups.filter((x) => x.kept);
  if (keptGroups.length < 2) return null;
  const effect = A.s / A.n - B.s / B.n;
  if (effect < 0 && !swapped) return diffPair(job, ctx, g, cell, b, a, true);   // name the side that is ahead overall first

  const n = A.n + B.n;
  const within = { a: 0, b: 0, effect: 0, se: 0 };
  for (const x of keptGroups) {
    x.share = (x.na + x.nb) / n;
    within.a += x.share * x.a;
    within.b += x.share * x.b;
    within.effect += x.share * x.effect;
    within.se += x.share ** 2 * x.v;
  }
  within.se = Math.sqrt(within.se);
  within.z = zscore(within.effect, within.se);
  const se = Math.sqrt(varMean(A.n, A.s, A.q) + varMean(B.n, B.s, B.q));
  return verdict({
    kind: "diff", binary, y: Y.name, x: X.name, z: ctx.cols[job.z].name, yi: job.y, xi: job.x, zi: job.z, binned: job.binned,
    positive: binary ? Y.levels[Y.positive] : null, a: X.levels[a], b: X.levels[b],
    key: ["diff", job.y, job.x, job.z, job.binned ? 1 : 0, X.levels[a], X.levels[b]].join("|"),
    n, dropped, minCell, groups,
    overall: { a: A.s / A.n + c0, b: B.s / B.n + c0, na: A.n, nb: B.n, effect, se, z: zscore(effect, se) },
    within,
    mix: effect - within.effect,
  }, keptGroups.map((x) => x.effect));
}

function diffJob(job, ctx) {
  const { cols, w, n } = ctx;
  const Y = cols[job.y], X = cols[job.x], g = groupsOf(job, ctx);
  const y = Y.kind === "binary" ? Y.y01 : Y.num;
  const c0 = Y.kind === "binary" ? 0 : Y.centre;
  const L = X.levels.length;
  const size = g.levels.length * L;
  const cell = { n: new Float64Array(size), s: new Float64Array(size), q: new Float64Array(size) };
  for (let i = 0; i < n; i++) {
    const a = X.codes[i], k = g.codes[i], v = y[i] - c0;
    const wt = w ? w[i] : 1;
    if (a < 0 || k < 0 || v !== v || !(wt > 0)) continue;
    const c = k * L + a;
    cell.n[c] += wt; cell.s[c] += wt * v; cell.q[c] += wt * v * v;
  }
  const out = [];
  for (let a = 0; a < L; a++) for (let b = a + 1; b < L; b++) {
    const r = diffPair(job, ctx, g, cell, a, b);
    if (r) out.push(r);
  }
  return out;
}

function slopeJob(job, ctx) {
  const { cols, w, n } = ctx;
  const X = cols[job.x], Y = cols[job.y], g = groupsOf(job, ctx);
  const G = g.levels.length;
  const sum = Array.from({ length: G }, () => ({ n: 0, x: 0, y: 0, xx: 0, xy: 0, yy: 0, lo: Infinity, hi: -Infinity }));
  for (let i = 0; i < n; i++) {
    const k = g.codes[i], x = X.num[i] - X.centre, y = Y.num[i] - Y.centre;
    const wt = w ? w[i] : 1;
    if (k < 0 || x !== x || y !== y || !(wt > 0)) continue;
    const s = sum[k];
    s.n += wt; s.x += wt * x; s.y += wt * y; s.xx += wt * x * x; s.xy += wt * x * y; s.yy += wt * y * y;
    if (x < s.lo) s.lo = x;
    if (x > s.hi) s.hi = x;
  }
  const least = Math.max(ctx.minCell, 3);
  const groups = [];
  const T = { n: 0, x: 0, y: 0, xx: 0, xy: 0, yy: 0 }, W = { xx: 0, xy: 0, yy: 0 };
  let dropped = 0, minCell = Infinity;
  sum.forEach((s, k) => {
    if (!s.n) return;
    const mx = s.x / s.n, my = s.y / s.n;
    const xx = s.xx - s.n * mx * mx, xy = s.xy - s.n * mx * my, yy = s.yy - s.n * my * my;
    const kept = s.n >= least && xx > 1e-12 * (1 + Math.abs(s.xx));
    const slope = kept ? xy / xx : NaN;
    groups.push({ level: g.levels[k], n: s.n, mx: mx + X.centre, my: my + Y.centre, effect: slope, intercept: my + Y.centre - slope * (mx + X.centre), r: kept && yy > 0 ? xy / Math.sqrt(xx * yy) : NaN, lo: s.lo + X.centre, hi: s.hi + X.centre, kept });
    if (!kept) { dropped += s.n; return; }
    for (const key of ["n", "x", "y", "xx", "xy", "yy"]) T[key] += s[key];
    W.xx += xx; W.xy += xy; W.yy += yy;
    minCell = Math.min(minCell, s.n);
  });
  const keptGroups = groups.filter((x) => x.kept);
  const mx = T.x / T.n, my = T.y / T.n;
  const xx = T.xx - T.n * mx * mx, xy = T.xy - T.n * mx * my, yy = T.yy - T.n * my * my;
  const df = T.n - keptGroups.length - 1;
  if (keptGroups.length < 2 || !(xx > 0) || !(W.xx > 0) || df < 1) return [];

  const effect = xy / xx;
  const se = Math.sqrt(Math.max(0, yy - (xy * xy) / xx) / (T.n - 2) / xx);
  const wEffect = W.xy / W.xx;
  const wSe = Math.sqrt(Math.max(0, W.yy - (W.xy * W.xy) / W.xx) / df / W.xx);
  const bxx = xx - W.xx;
  return [verdict({
    kind: "slope", binary: false, y: Y.name, x: X.name, z: cols[job.z].name, yi: job.y, xi: job.x, zi: job.z, binned: job.binned,
    key: ["slope", job.y, job.x, job.z, job.binned ? 1 : 0].join("|"),
    n: T.n, dropped, minCell, groups,
    overall: { effect, intercept: my + Y.centre - effect * (mx + X.centre), r: yy > 0 ? xy / Math.sqrt(xx * yy) : NaN, se, z: zscore(effect, se) },
    within: { effect: wEffect, r: W.yy > 0 ? W.xy / Math.sqrt(W.xx * W.yy) : NaN, se: wSe, z: zscore(wEffect, wSe) },
    between: { effect: bxx > 1e-12 * xx ? (xy - W.xy) / bxx : NaN },
  }, keptGroups.map((x) => x.effect))];
}

/** Run one planned triple. Returns zero or more comparisons. */
export const runJob = (job, ctx) => (job.kind === "slope" ? slopeJob(job, ctx) : diffJob(job, ctx));

/** Reversals first, then by strength: how many standard errors the weaker of the two effects is from zero. */
export const rank = (list) => [...list].sort((p, q) => (q.reversal ? 1 : 0) - (p.reversal ? 1 : 0) || q.strength - p.strength);

/** The whole search in one call (the page runs the same jobs in slices so it stays responsive). */
export function search(table, cols, { weight = null, minCell = 5, thirds: bin = true } = {}) {
  const ctx = context(table, cols, { weight, minCell });
  if (ctx.error) return { error: ctx.error };
  const { jobs, skipped } = plan(cols, { weight, thirds: bin });
  const comparisons = rank(jobs.flatMap((j) => runJob(j, ctx)));
  return { ctx, jobs: jobs.length, skipped, comparisons, reversals: comparisons.filter((c) => c.reversal) };
}

/** Text straight to results, with the count column guessed unless one is given. */
export function analyse(text, options = {}) {
  const table = parseTable(text);
  if (table.error) return { error: table.error };
  const cols = profile(table);
  const weight = options.weight === undefined ? guessWeight(cols, table.n) : options.weight;
  const found = search(table, cols, { ...options, weight });
  return found.error ? { error: found.error } : { table, cols, weight, ...found };
}
