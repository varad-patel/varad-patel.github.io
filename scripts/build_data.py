"""Generate 365projects/challenge-data.js from the list, the built projects and the config.

    python scripts/build_data.py

The page reads one JavaScript file instead of fetching JSON, so index.html also
works when opened straight from disk. Run this after import_projects.py or after
changing the start date in data/site.json. It fails loudly if anything is
inconsistent (missing thumbnail, unknown project, gaps in the numbering).
"""

from __future__ import annotations

import csv
import json
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "365projects" / "challenge-data.js"


def load() -> tuple[dict, list[dict], list[dict], list[dict]]:
    site = json.loads((ROOT / "data" / "site.json").read_text(encoding="utf-8"))
    sections = json.loads((ROOT / "data" / "sections.json").read_text(encoding="utf-8"))
    with open(ROOT / "data" / "challenge.tsv", encoding="utf-8", newline="") as fh:
        rows = list(csv.DictReader(fh, delimiter="\t"))
    built = json.loads((ROOT / "data" / "built.json").read_text(encoding="utf-8"))
    return site, sections, rows, built


def assemble(site: dict, sections: list[dict], rows: list[dict], built: list[dict], img_dir: Path | None = None) -> dict:
    img_dir = img_dir or ROOT / "365projects" / "img"
    start = date.fromisoformat(site["start"])
    by_id = {b["id"]: b for b in built}
    ids = [int(r["id"]) for r in rows]
    if ids != list(range(1, len(ids) + 1)):
        raise ValueError("project numbers in data/challenge.tsv must run 1..N without gaps")
    unknown = sorted(set(by_id) - set(ids))
    if unknown:
        raise ValueError(f"built projects not in the list: {unknown}")
    section_ids = {s["id"] for s in sections}

    projects = []
    for row in rows:
        number = int(row["id"])
        if int(row["section"]) not in section_ids:
            raise ValueError(f"project {number} has unknown section {row['section']}")
        item = {
            "id": number,
            "title": row["title"],
            "desc": row["description"],
            "section": int(row["section"]),
            "date": (start + timedelta(days=number - 1)).isoformat(),
        }
        if number in by_id:
            b = by_id[number]
            image = f"img/{number:03d}.jpg"
            if not (img_dir / f"{number:03d}.jpg").exists():
                raise FileNotFoundError(f"missing thumbnail for project {number}: {img_dir / f'{number:03d}.jpg'}")
            item.update(
                built=b["built"], slug=b["slug"], question=b["question"], finding=b["finding"],
                limit=b["limit"], sources=b["sources"], img=image,
            )
        projects.append(item)

    return {
        "start": site["start"],
        "repo": site["repo"],
        "branch": site["branch"],
        "sections": sections,
        "projects": projects,
    }


def main() -> None:
    data = assemble(*load())
    OUT.write_text(
        "// Generated by scripts/build_data.py. Do not edit by hand.\n"
        "window.CHALLENGE = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )
    done = sum(1 for p in data["projects"] if "built" in p)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(data['projects'])} projects, {done} built, day 1 = {data['start']}")


if __name__ == "__main__":
    main()
