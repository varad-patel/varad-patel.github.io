// Build 365projects/69/critical.js: lag orders and simulated critical values for the bubble tests of project 69.
//
//   node scripts/data/bubble_critical.mjs [--reps 10000]
//
// Run scripts/data/bubble_series.py first; this script reads the series from 365projects/69/data.js and the test
// code from 365projects/69/logic.js, so the page and its critical values always use the same arithmetic.
//
// Lag order. For each series the number k of lagged differences in the ADF regressions is chosen once, on the whole
// sample of log values, by the Bayesian information criterion over k = 0..6 (logic.js, chooseLag). Monthly averages
// of a random walk have changes that are correlated (about 0.25 at one month), and without lags the tests then
// raise false alarms far too often; the page shows this.
//
// Critical values (Phillips, Shi and Yu 2015, section 2 and Table 1): for each sample size T and lag order k in use,
// simulate `reps` random walks with an asymptotically negligible drift, y_t = 1/T + y_{t-1} + e_t with e_t standard
// normal (their d = eta = 1), run the same ADF regressions as the page (intercept, k lags, smallest window 36
// observations), and keep the percentiles 1 to 99 of SADF, GSADF and of BSADF at the last observation, and the 90th,
// 95th and 99th percentiles of BSADF at every end point. The generator is the kit's seeded mulberry32 with seed
// 6900000 + 10 T + k, so a rerun writes the same file. Values are rounded to four decimals.
//
// As a check on the code, the script also reruns PSY's own design for T = 400 with a smallest window of 40 and no
// lags (their Table 1(c), r0 = 0.1) and prints the 90%, 95% and 99% critical values next to theirs.

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { SERIES } from "../../365projects/69/data.js";
import { MIN_WINDOW, simulateNull, criticalValue, chooseLag } from "../../365projects/69/logic.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const OUT = join(ROOT, "365projects", "69", "critical.js");
const repsArg = process.argv.indexOf("--reps");
const REPS = repsArg > 0 ? Number(process.argv[repsArg + 1]) : 10000;
const KMAX = 6;
const round = (v) => (v == null ? null : Math.round(v * 1e4) / 1e4);
const levels = (p) => [0.9, 0.95, 0.99].map((l) => criticalValue(p, l).toFixed(2)).join(" / ");

const series = {};
for (const s of SERIES.series) {
  const c = chooseLag(s.values.map(Math.log), KMAX);
  series[s.id] = { T: s.values.length, k: c.k, bic: c.bic.map((v) => Math.round(v * 100) / 100) };
  console.log(`${s.id}: T = ${s.values.length}, BIC chooses k = ${c.k}`);
}

const dist = {};
for (const key of [...new Set(Object.values(series).map((s) => `${s.T}-${s.k}`))].sort()) {
  const [T, k] = key.split("-").map(Number);
  const t0 = Date.now();
  const s = simulateNull(T, MIN_WINDOW, REPS, 6900000 + 10 * T + k, { k });
  dist[key] = {
    T, k, seed: s.seed, gsadf: s.gsadf.map(round), sadf: s.sadf.map(round), bsadfEnd: s.bsadfEnd.map(round),
    cv90: s.cv90.map(round), cv95: s.cv95.map(round), cv99: s.cv99.map(round),
  };
  console.log(`T = ${T}, k = ${k}: SADF ${levels(s.sadf)}, GSADF ${levels(s.gsadf)}  (${((Date.now() - t0) / 1000).toFixed(0)} s)`);
}

const check = simulateNull(400, 40, REPS, 6900400);
console.log(`PSY Table 1(c), T = 400, r0 = 0.1: SADF ${levels(check.sadf)} (published 1.19 / 1.50 / 1.98), GSADF ${levels(check.gsadf)} (published 1.97 / 2.21 / 2.71)`);

const out = {
  reps: REPS, w0: MIN_WINDOW, kmax: KMAX,
  dgp: "y_t = 1/T + y_{t-1} + e_t, e_t ~ N(0, 1); ADF regressions with an intercept and k lagged differences",
  psyCheck: { T: 400, w0: 40, k: 0, sadf: [0.9, 0.95, 0.99].map((l) => round(criticalValue(check.sadf, l))), gsadf: [0.9, 0.95, 0.99].map((l) => round(criticalValue(check.gsadf, l))) },
  series, dist,
};
writeFileSync(OUT,
  "// Generated by scripts/data/bubble_critical.mjs. Do not edit by hand.\n"
  + `// Lag orders chosen by BIC, and simulated null distributions of the SADF, GSADF and BSADF statistics: ${REPS} random walks\n`
  + `// for each sample size and lag order, smallest window ${MIN_WINDOW}. Percentile arrays hold percentiles 1..99; cv90/cv95/cv99[b]\n`
  + "// are critical values of BSADF for windows ending at observation b. dist is keyed by \"T-k\".\n"
  + "export const CRITICAL = " + JSON.stringify(out) + ";\n");
console.log("wrote 365projects/69/critical.js");
