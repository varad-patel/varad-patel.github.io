"""Build 365projects/34/data.js, the Big Mac prices behind project 34.

    python scripts/data/bigmac.py [--cache DIR]

Source (downloaded into --cache, never committed):
  The Economist, "The Big Mac index", https://github.com/TheEconomist/big-mac-data, at the commit named
  in COMMIT below (the July 2026 update). Three files are read:
    * source-data/big-mac-source-data-v2.csv   the inputs: local price of a Big Mac, local currency per
                                               US dollar, GDP per person in local currency, by country and date
    * output-data/big-mac-full-index.csv       The Economist's own results, kept for the tests
    * data-generator-v3.R                      the calculation, read only for its lists of countries

Licence, from the repository's README: "The data generated by The Economist are available under the
Creative Commons Attribution 4.0 International License." The README adds that the licences "do not cover
any Economist content or third-party data or content made available using the software". The same README
gives the origin of the inputs: Big Mac prices from McDonald's and The Economist's reporting, exchange rates
from Thomson Reuters and Refinitiv Datastream, GDP per person from the IMF World Economic Outlook. So the
Creative Commons licence covers The Economist's own figures (its calculated index, kept here for the tests,
and the prices its reporting gathered) and does not cover the exchange rates, the GDP figures or the prices
McDonald's supplied, for which the repository states no terms. The page says exactly this.

Cleaning rules:
  * Rows with no local price are dropped, as the generator script does.
  * A row whose local price or exchange rate is 0 is dropped too. There is one, Venezuela in January 2018,
    where 0 stands for "no observation"; the generator leaves it out of the index because 0 / 0 is not a number.
  * A GDP figure given as "#N/A" becomes null. Nothing is filled in.
  * A country keeps the name it has on its latest date ("United Arab Emirates", once "UAE").
  * Numbers are written exactly as published: the index is rounded to five places by The Economist, and
    reproducing that needs the inputs unrounded.
  * The lists of countries in the index and in the GDP regression are read out of the generator script, so
    they cannot drift from the source. The two dates from which later countries join the regression
    (2021-01-01 and 2026-07-01) are checked to be present in the script.
"""

from __future__ import annotations

import argparse
import csv
import datetime
import json
import re
import tempfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "365projects" / "34" / "data.js"
UA = {"User-Agent": "varad-patel-365projects/1.0 (https://varad-patel.github.io)"}
COMMIT = "0d9710454755a71d7f0c03e662e580b271be456d"
BASE = f"https://raw.githubusercontent.com/TheEconomist/big-mac-data/{COMMIT}/"
FILES = {
    "big-mac-source-data-v2.csv": "source-data/big-mac-source-data-v2.csv",
    "big-mac-full-index.csv": "output-data/big-mac-full-index.csv",
    "data-generator-v3.R": "data-generator-v3.R",
}
MISSING = {"", "NA", "#N/A"}


def fetch(name: str, cache: Path) -> Path:
    path = cache / name
    if not path.exists():
        with urllib.request.urlopen(urllib.request.Request(BASE + FILES[name], headers=UA), timeout=120) as r:
            path.write_bytes(r.read())
    return path


def num(text: str):
    """A number exactly as published: an int when it is one, otherwise a float (repr round-trips)."""
    if text in MISSING:
        return None
    value = float(text)
    return int(value) if value.is_integer() and "." not in text and "e" not in text.lower() else value


def vector(source: str, name: str) -> list[str]:
    """The quoted strings inside `name <- c(...)` in the R script."""
    match = re.search(rf"^{re.escape(name)}\s*<-\s*c\((.*?)\)", source, re.S | re.M)
    if not match:
        raise SystemExit(f"{name} not found in the generator script")
    return re.findall(r'"([A-Z]{3})"', match.group(1))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", default=None)
    ap.add_argument("--retrieved", default=None, help="date the files were downloaded, if the cache is older than today")
    args = ap.parse_args()
    cache = Path(args.cache) if args.cache else Path(tempfile.mkdtemp())
    cache.mkdir(parents=True, exist_ok=True)

    with fetch("big-mac-source-data-v2.csv", cache).open(encoding="utf-8", newline="") as f:
        source = [r for r in csv.DictReader(f) if r["local_price"] not in MISSING]
    source = [r for r in source if float(r["local_price"]) > 0 and r["dollar_ex"] not in MISSING and float(r["dollar_ex"]) > 0]
    with fetch("big-mac-full-index.csv", cache).open(encoding="utf-8", newline="") as f:
        full = list(csv.DictReader(f))
    script = fetch("data-generator-v3.R", cache).read_text(encoding="utf-8")

    for needed in ('date >= as.Date("2021-01-01")', 'date >= as.Date("2026-07-01")', "lm(dollar_price ~ GDP_bigmac)"):
        if needed not in script:
            raise SystemExit(f"the generator script no longer contains {needed!r}: read it again before rebuilding")

    dates = sorted({r["date"] for r in source})
    names = {}
    for r in sorted(source, key=lambda r: r["date"]):
        names[r["iso_a3"]] = r["name"]

    prices, published = [], []
    for date in dates:
        rows = sorted((r for r in source if r["date"] == date), key=lambda r: r["iso_a3"])
        prices.append([[r["iso_a3"], r["currency_code"], num(r["local_price"]), num(r["dollar_ex"]), num(r["GDP_local"])] for r in rows])
        out = sorted((r for r in full if r["date"] == date), key=lambda r: r["iso_a3"])
        published.append([[r["iso_a3"], num(r["USD_raw"]), num(r["USD_adjusted"])] for r in out])

    data = {
        "source": "The Economist, The Big Mac index, https://github.com/TheEconomist/big-mac-data",
        "licence": "CC BY 4.0 for the data generated by The Economist only. Its licence statement excludes third-party data, and by its own account the exchange rates (Thomson Reuters, Refinitiv Datastream), GDP per person (IMF World Economic Outlook) and the Big Mac prices supplied by McDonald's are third-party: no terms are stated for those",
        "commit": COMMIT,
        "retrieved": args.retrieved or datetime.date.today().isoformat(),
        "dates": dates,
        "names": dict(sorted(names.items())),
        "indexCountries": vector(script, "big_mac_countries"),
        "regression": {
            "always": vector(script, "regression_countries"),
            "from": {"2021-01-01": vector(script, "regression_addons_2021"), "2026-07-01": vector(script, "regression_addons_2026")},
        },
    }
    head = json.dumps(data, ensure_ascii=False, indent=2)[:-2]
    lines = lambda table: ",\n".join("    " + json.dumps(row, ensure_ascii=False, separators=(",", ":")) for row in table)
    text = (
        "// GENERATED by scripts/data/bigmac.py. Do not edit by hand.\n"
        "// The Economist's Big Mac index: the inputs it is calculated from and, for the tests, its published results.\n"
        "// prices: one list per date, in the order of `dates`. Each row is\n"
        "//   [ISO country code, currency code, local price of a Big Mac, local currency per US dollar, GDP per person in local currency or null].\n"
        "// published: The Economist's own index against the US dollar, [ISO country code, raw, GDP-adjusted or null].\n"
        f"export const BIGMAC = {head},\n"
        f'  "prices": [\n{lines(prices)}\n  ],\n'
        f'  "published": [\n{lines(published)}\n  ]\n'
        "};\n"
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(dates)} dates, {sum(len(p) for p in prices)} prices, {sum(len(p) for p in published)} published rows, {len(text) / 1024:.0f} KB")


if __name__ == "__main__":
    main()
