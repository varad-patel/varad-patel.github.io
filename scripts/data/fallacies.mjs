// Train the Day 13 fallacy classifier and write 365projects/13/model.js.
//
//   node scripts/data/fallacies.mjs [path/to/arguments-en-2018-01-15.tsv]
//
// Data: Argotario (Habernal, Hannemann, Pollak, Klamm, Pauli and Gurevych, 2017), English arguments,
// https://github.com/UKPLab/argotario, released under CC0. Each row is a short argument written by a
// player of a game who was asked to commit a particular fallacy (or none). The label used here is that
// intended fallacy. Without a path the file is downloaded.
//
// The script trains on everything for the shipped model, and separately runs 5-fold cross-validation
// so that the page can report how often the detector is wrong on arguments it has not seen.

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { rng } from "../../365projects/kit/kit.js";
import { train, prepare, predict, folds, score } from "../../365projects/13/logic.js";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const URL_ = "https://raw.githubusercontent.com/UKPLab/argotario/master/data/arguments-en-2018-01-15.tsv";
const LABELS = ["No Fallacy", "Ad Hominem", "Appeal to Emotion", "Hasty Generalization", "Irrelevant Authority", "Red Herring"];
const OPTIONS = { minDf: 2, epochs: 300, rate: 4, l2: 0.0005, balance: 0.5, labels: LABELS };

const path = process.argv[2];
const raw = path ? await readFile(path, "utf8") : await (await fetch(URL_, { headers: { "User-Agent": "varad-patel-365projects/1.0" } })).text();
const lines = raw.split(/\r?\n/).map((l) => l.split("\t")).filter((c) => c.length === 9);
const header = lines.shift();
const col = (name) => header.indexOf(name);
let rows = lines.map((c) => ({ text: c[col("Text")].trim(), label: c[col("Intended Fallacy")].trim() }))
  .filter((r) => LABELS.includes(r.label) && r.text.split(/\s+/).length >= 4);
// The same text can appear more than once; keep the first so that a copy cannot leak between folds.
const seen = new Set();
rows = rows.filter((r) => { const k = r.text.toLowerCase(); if (seen.has(k)) return false; seen.add(k); return true; });
rows = rng(13).shuffle(rows);

// Cross-validation.
const K = 5;
const fold = folds(rows, K);
const truth = [], guess = [], confidence = [];
for (let f = 0; f < K; f++) {
  const model = prepare(train(rows.filter((_, i) => fold[i] !== f), OPTIONS));
  rows.forEach((r, i) => {
    if (fold[i] !== f) return;
    const top = predict(model, r.text).ranked[0];
    truth.push(r.label); guess.push(top.label); confidence.push(top.p);
  });
}
const cv = score(LABELS, truth, guess);
const counts = Object.fromEntries(LABELS.map((l) => [l, rows.filter((r) => r.label === l).length]));
const majority = Math.max(...Object.values(counts)) / rows.length;
const binary = truth.filter((t, i) => (t === "No Fallacy") === (guess[i] === "No Fallacy")).length / truth.length;

// The shipped model: trained on every row, weights rounded, features with no real weight dropped.
const full = train(rows, OPTIONS);
const keep = full.vocab.map((_, j) => Math.max(...full.weights.map((w) => Math.abs(w[j]))) >= 0.05);
const round = (v) => Math.round(v * 1000) / 1000;
const model = {
  labels: LABELS,
  vocab: full.vocab.filter((_, j) => keep[j]),
  idf: full.idf.filter((_, j) => keep[j]).map(round),
  weights: full.weights.map((w) => w.filter((_, j) => keep[j]).map(round)),
  bias: full.bias.map(round),
};

const out = {
  source: "Argotario (Habernal et al., 2017), English arguments, CC0. https://github.com/UKPLab/argotario",
  trained: "2026-10-10",
  rows: rows.length,
  counts,
  evaluation: {
    method: "5-fold stratified cross-validation",
    accuracy: round(cv.accuracy), macroF1: round(cv.macroF1), majorityBaseline: round(majority), fallacyOrNot: round(binary),
    perLabel: cv.perLabel.map((l) => ({ label: l.label, n: l.n, called: l.called, precision: round(l.precision), recall: round(l.recall), f1: round(l.f1) })),
    matrix: cv.matrix,
    // [confidence of the top guess, 1 if it was right] for every held-out argument, for the confidence chart.
    pairs: confidence.map((c, i) => [Math.round(c * 100) / 100, truth[i] === guess[i] ? 1 : 0]),
  },
  model,
};
const file = join(ROOT, "365projects", "13", "model.js");
await writeFile(file,
  "// Generated by scripts/data/fallacies.mjs from the Argotario dataset (CC0). Do not edit by hand.\n"
  + "export const FALLACY_MODEL = " + JSON.stringify(out) + ";\n", "utf8");

console.log(`rows ${rows.length}`, counts);
console.log(`cross-validated accuracy ${(cv.accuracy * 100).toFixed(1)}% (majority baseline ${(majority * 100).toFixed(1)}%), macro F1 ${cv.macroF1.toFixed(3)}, fallacy-or-not ${(binary * 100).toFixed(1)}%`);
for (const l of cv.perLabel) console.log(`  ${l.label.padEnd(22)} n=${String(l.n).padStart(3)} precision ${(l.precision * 100).toFixed(0)}% recall ${(l.recall * 100).toFixed(0)}%`);
console.log(`features kept ${model.vocab.length} of ${full.vocab.length}; wrote ${file} (${Math.round(JSON.stringify(out).length / 1024)} KB)`);
